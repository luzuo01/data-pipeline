"""Import the PORTAL-Trace robot FBX files into the UE5 project.

Run this script from the UE5.6.1 Python console, or headlessly with
``UnrealEditor-Cmd.exe -ExecutePythonScript=...``.  The source FBX files are
generated by ``materialize_portal_ue_assets.py``.  Importing them creates real
``.uasset`` StaticMesh assets under ``/Game/Robots/PORTALTrace``; it does not
turn a combined mesh into a physically articulated robot.
"""

from __future__ import annotations

import json
from pathlib import Path

import unreal  # type: ignore


PROJECT_ROOT = Path(unreal.Paths.project_dir())
SOURCE_ROOT = PROJECT_ROOT / "Content" / "Robots" / "PORTALTrace"
ROBOTS = ("Panda", "Sawyer", "IIWA", "Kinova3", "XArm7", "UR5e")


def _fbx_options():
    options = unreal.FbxImportUI()
    options.import_mesh = True
    options.import_as_skeletal = False
    options.import_materials = True
    options.import_textures = True
    options.mesh_type_to_import = unreal.FBXImportType.FBXIT_STATIC_MESH
    # Each FBX contains all visible robot links.  Combining them gives the
    # scene builder one predictable preview asset per robot instead of dozens
    # of link meshes with importer-generated names.
    # UE5 exposes this switch on the static-mesh import-data object in some
    # builds and directly on FbxImportUI in others.
    try:
        options.combine_meshes = True
    except Exception:
        pass
    try:
        options.static_mesh_import_data.combine_meshes = True
    except Exception:
        try:
            options.static_mesh_import_data.set_editor_property("combine_meshes", True)
        except Exception:
            pass
    options.set_editor_property("automated_import_should_detect_type", False)
    return options


def import_all() -> dict:
    tools = unreal.AssetToolsHelpers.get_asset_tools()
    report = {"project": str(PROJECT_ROOT), "robots": {}, "errors": []}
    for robot in ROBOTS:
        source = SOURCE_ROOT / robot / f"{robot}.fbx"
        destination = f"/Game/Robots/PORTALTrace/{robot}"
        if not source.is_file():
            report["errors"].append(f"missing source: {source}")
            continue
        task = unreal.AssetImportTask()
        task.filename = str(source)
        task.destination_path = destination
        task.destination_name = robot
        task.automated = True
        task.replace_existing = True
        task.save = True
        task.options = _fbx_options()
        tools.import_asset_tasks([task])
        imported = list(task.imported_object_paths or [])
        expected = f"{destination}/{robot}.{robot}"
        report["robots"][robot] = {
            "source": str(source),
            "destination": destination,
            "expected_asset": expected,
            "imported_object_paths": imported,
            "status": "imported" if expected in imported else "import_requested",
            "asset_kind": "StaticMesh",
            "articulated": False,
        }
    output = SOURCE_ROOT / "ue_import_report.json"
    output.write_text(json.dumps(report, ensure_ascii=False, indent=2), encoding="utf-8")
    unreal.log(f"PORTAL-Trace UE import report: {output}")
    return report


if __name__ == "__main__":
    import_all()
